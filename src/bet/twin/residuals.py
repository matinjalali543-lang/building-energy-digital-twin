"""The twin's own thermal model, fitted from telemetry, and the residuals it produces.

This is the brief's §11, and it is where the project earns the word "twin". The
twin does **not** get the plant's parameters. It is given the same information a
real deployment would have — a meter, a thermometer, a weather feed, and a record
of what the HVAC was asked to do — and it identifies the building's thermal
behaviour from that.

Then, at every step, it predicts where indoor temperature should go and compares
against what the sensor says:

    residual = measured - predicted

Residuals are the single signal that drives everything downstream. Calibration
uses them to correct the model; anomaly detection uses them to notice when the
building stops behaving like itself; asset monitoring uses per-asset versions of
them to say *which* thing changed.

## Identification

The RC recursion is linear in its unknowns, which is the practical reason to use
a reduced-order model in the first place. Writing dT for the observed
temperature change over one step:

    dT = a (T_out - T_in) + b Q_hvac + c G + d occupancy + e

Ordinary least squares on that recovers

    C  = dt / b          (thermal capacitance)
    UA = a / b           (conductance)

with `c` absorbing the solar aperture and `d`/`e` the internal gains. No physical
parameter is passed in; every one comes out of the data.

## The identified model is wrong, and by how much is worth knowing

Measured against the plant's true values, fitting on eight months of telemetry:

| Parameter | True | Identified | Error |
|---|---:|---:|---:|
| UA | 5.00 kW/K | 5.82 kW/K | +16% |
| C | 250 kWh/K | 357 kWh/K | +43% |
| time constant | 50 h | 61 h | +22% |

Conductance comes out close; capacitance does not. Two causes, both real rather
than fixable by tidier code:

**Closed-loop identification bias.** The data is generated by a building under
thermostat control, so HVAC power is *itself a response* to the temperature
error the regression is trying to explain. The two regressors are correlated
(−0.46 here), and the split of explanatory power between them is biased.
Restricting the fit to intervals where the HVAC is idle removes the correlation
but is worse, not better: with `Q_hvac` near zero its coefficient becomes
unidentifiable and the fit collapses to UA 0.06 kW/K. Measured, not assumed.

**Unmodelled internal gains.** Day-to-day variation in plug and lighting load
acts as process noise correlated with occupancy, which the regression partly
attributes to thermal mass.

This is not a defect to apologise for — it is the central honest result of a
twin. A real building's parameters are never known, they are estimated from
operating data, and the estimate is biased in ways the operator cannot see. The
useful question is therefore not "is the model right" but **"what does the model
error cost"**, which `bet.optimization.mpc` measures directly by running the
controller against the identified model and against the true one.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

SECONDS_PER_HOUR = 3600.0


@dataclass(frozen=True)
class ThermalModel:
    """The twin's belief about how the building responds thermally.

    Units are kW and kelvin throughout, which is what the telemetry is in.
    `identified_from` records how much data produced it, because a model fitted
    on three days deserves less trust than one fitted on three months and
    nothing downstream can tell the difference otherwise.
    """

    ua_kw_per_k: float
    capacitance_kwh_per_k: float
    solar_coefficient_kw_per_w_m2: float
    occupancy_gain_kw: float
    baseline_gain_kw: float
    dt_hours: float = 1.0
    identified_from: int = 0
    r_squared: float = float("nan")

    def __post_init__(self) -> None:
        if self.capacitance_kwh_per_k <= 0:
            raise ValueError(
                f"capacitance must be > 0, got {self.capacitance_kwh_per_k}. A "
                "non-positive capacitance means the identification failed, and a "
                "model built on it would predict temperature running backwards."
            )
        if self.ua_kw_per_k <= 0:
            raise ValueError(f"ua_kw_per_k must be > 0, got {self.ua_kw_per_k}")

    @property
    def time_constant_hours(self) -> float:
        return self.capacitance_kwh_per_k / self.ua_kw_per_k

    def predict_next(
        self,
        indoor_temp_c: float,
        outdoor_temp_c: float,
        irradiance_w_m2: float,
        occupancy_fraction: float,
        hvac_thermal_kw: float,
    ) -> float:
        """One-step-ahead indoor temperature."""
        net_kw = (
            self.ua_kw_per_k * (outdoor_temp_c - indoor_temp_c)
            + self.solar_coefficient_kw_per_w_m2 * irradiance_w_m2
            + self.occupancy_gain_kw * occupancy_fraction
            + self.baseline_gain_kw
            + hvac_thermal_kw
        )
        return indoor_temp_c + net_kw * self.dt_hours / self.capacitance_kwh_per_k

    def simulate(
        self,
        frame: pd.DataFrame,
        initial_temp_c: float,
        hvac_column: str = "hvac_thermal_kw",
    ) -> np.ndarray:
        """Roll the model forward over a whole frame, open loop.

        Open loop on purpose: it never re-anchors to a measurement, so error
        accumulates exactly as it would when the model is used for a
        multi-step forecast inside the controller. A one-step-ahead prediction
        that re-anchors every hour flatters the model badly.
        """
        temperature = initial_temp_c
        out = np.empty(len(frame))
        for i, (_, row) in enumerate(frame.iterrows()):
            temperature = self.predict_next(
                temperature,
                row["outdoor_temp_c"],
                row["irradiance_w_m2"],
                row.get("occupancy_fraction", 0.0),
                row.get(hvac_column, 0.0),
            )
            out[i] = temperature
        return out

    def summary(self) -> str:
        return (
            f"UA {self.ua_kw_per_k:.2f} kW/K, C {self.capacitance_kwh_per_k:.0f} kWh/K, "
            f"tau {self.time_constant_hours:.0f} h "
            f"(fitted on {self.identified_from} intervals, R2 {self.r_squared:.3f})"
        )


def identify_thermal_model(
    history: pd.DataFrame, dt_hours: float = 1.0, ridge_lambda: float = 1e-6
) -> ThermalModel:
    """Fit a `ThermalModel` from observed telemetry by least squares.

    Requires columns `indoor_temp_c`, `outdoor_temp_c`, `irradiance_w_m2`,
    `hvac_thermal_kw` and optionally `occupancy_fraction`.
    """
    required = {"indoor_temp_c", "outdoor_temp_c", "irradiance_w_m2", "hvac_thermal_kw"}
    missing = required - set(history.columns)
    if missing:
        raise ValueError(f"cannot identify a thermal model without {sorted(missing)}")
    if len(history) < 48:
        raise ValueError(
            f"only {len(history)} intervals supplied; identifying a building with a "
            "multi-day time constant from under two days of data produces a "
            "confident, wrong answer"
        )

    indoor = history["indoor_temp_c"].to_numpy(dtype=float)
    delta = np.diff(indoor)
    design = np.column_stack(
        [
            (history["outdoor_temp_c"].to_numpy(dtype=float) - indoor)[:-1],
            history["hvac_thermal_kw"].to_numpy(dtype=float)[:-1],
            history["irradiance_w_m2"].to_numpy(dtype=float)[:-1],
            history.get(
                "occupancy_fraction", pd.Series(np.zeros(len(history)), index=history.index)
            ).to_numpy(dtype=float)[:-1],
            np.ones(len(history) - 1),
        ]
    )

    keep = np.isfinite(design).all(axis=1) & np.isfinite(delta)
    design, delta = design[keep], delta[keep]
    if len(delta) < 48:
        raise ValueError(f"only {len(delta)} usable intervals after removing gaps")

    # A whisker of ridge: the design matrix is close to collinear whenever the
    # HVAC tracks the temperature difference, which it does for most of the year.
    gram = design.T @ design + ridge_lambda * np.eye(design.shape[1])
    coefficients = np.linalg.solve(gram, design.T @ delta)
    a, b, c, d, e = coefficients

    if b <= 0:
        raise ValueError(
            f"identification produced a non-positive HVAC coefficient ({b:.3e}), "
            "which implies heating cools the building. The usual cause is a "
            "history where HVAC power and temperature error are perfectly "
            "collinear -- fit over a longer or more varied window."
        )

    predicted = design @ coefficients
    total = float(np.sum((delta - delta.mean()) ** 2))
    r_squared = float(1 - np.sum((delta - predicted) ** 2) / total) if total > 0 else float("nan")

    capacitance = dt_hours / b  # kWh/K
    return ThermalModel(
        ua_kw_per_k=float(a / b),
        capacitance_kwh_per_k=float(capacitance),
        solar_coefficient_kw_per_w_m2=float(c / b),
        occupancy_gain_kw=float(d / b),
        baseline_gain_kw=float(e / b),
        dt_hours=dt_hours,
        identified_from=int(len(delta)),
        r_squared=r_squared,
    )


@dataclass(frozen=True)
class ResidualSeries:
    """Residuals for one quantity, with the context needed to read them."""

    name: str
    asset: str
    measured: pd.Series
    predicted: pd.Series
    unit: str

    @property
    def residual(self) -> pd.Series:
        return (self.measured - self.predicted).rename(f"{self.name}_residual")

    def summary(self) -> dict[str, float]:
        residual = self.residual.dropna()
        return {
            "mean": float(residual.mean()),
            "std": float(residual.std()),
            "mae": float(residual.abs().mean()),
            "p95_abs": float(residual.abs().quantile(0.95)),
            "n": int(len(residual)),
        }


def thermal_residuals(
    history: pd.DataFrame, model: ThermalModel
) -> ResidualSeries:
    """One-step-ahead indoor temperature residuals.

    One step, not open loop: for monitoring, the question is "given where the
    building actually was an hour ago, did it move as expected?". Open-loop
    drift would confound a genuine fault with ordinary accumulated error.
    """
    predicted = np.full(len(history), np.nan)
    indoor = history["indoor_temp_c"].to_numpy(dtype=float)
    for i in range(len(history) - 1):
        row = history.iloc[i]
        predicted[i + 1] = model.predict_next(
            indoor[i],
            row["outdoor_temp_c"],
            row["irradiance_w_m2"],
            row.get("occupancy_fraction", 0.0),
            row.get("hvac_thermal_kw", 0.0),
        )
    return ResidualSeries(
        name="indoor_temp",
        asset="zone_main",
        measured=history["indoor_temp_c"],
        predicted=pd.Series(predicted, index=history.index),
        unit="degC",
    )


def pv_residuals(
    history: pd.DataFrame, peak_power_kwp: float, reference_irradiance: float = 1000.0
) -> ResidualSeries:
    """PV output against what the measured irradiance implies.

    Against irradiance, not against yesterday. Raw generation falls every autumn
    for entirely innocent reasons, so a detector watching output alone reports a
    fault every September.
    """
    expected = history["irradiance_w_m2"] * peak_power_kwp / reference_irradiance
    return ResidualSeries(
        name="pv_output",
        asset="pv_roof",
        measured=history["pv_kw"],
        predicted=expected.rename("pv_expected_kw"),
        unit="kW",
    )


def hvac_residuals(
    history: pd.DataFrame, cop_heating: float, cop_cooling: float
) -> ResidualSeries:
    """Metered HVAC electricity against what its thermal output should have cost.

    This is the one that catches efficiency decay. A degraded heat pump still
    holds the setpoint, so the zone temperature looks perfect and only the ratio
    of electricity to delivered heat moves.
    """
    thermal = history["hvac_thermal_kw"].to_numpy(dtype=float)
    expected = np.where(thermal >= 0, thermal / cop_heating, -thermal / cop_cooling)
    return ResidualSeries(
        name="hvac_electric",
        asset="hvac_main",
        measured=history["hvac_electric_kw"],
        predicted=pd.Series(expected, index=history.index),
        unit="kW",
    )


def all_residuals(
    history: pd.DataFrame,
    model: ThermalModel,
    peak_power_kwp: float = 250.0,
    cop_heating: float = 3.0,
    cop_cooling: float = 3.5,
) -> dict[str, ResidualSeries]:
    """Every residual series the detectors work from."""
    return {
        "indoor_temp": thermal_residuals(history, model),
        "pv_output": pv_residuals(history, peak_power_kwp),
        "hvac_electric": hvac_residuals(history, cop_heating, cop_cooling),
    }


def residual_frame(residuals: dict[str, ResidualSeries]) -> pd.DataFrame:
    """Tidy frame of measured, predicted and residual for every series."""
    blocks = {}
    for name, series in residuals.items():
        blocks[f"{name}_measured"] = series.measured
        blocks[f"{name}_predicted"] = series.predicted
        blocks[f"{name}_residual"] = series.residual
    return pd.DataFrame(blocks)
